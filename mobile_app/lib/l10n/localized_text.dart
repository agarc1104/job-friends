import 'package:flutter/widgets.dart';

const Set<String> _supportedLanguageCodes = {'en', 'es', 'pt', 'fr', 'de', 'it'};

String languageCodeFromLocale(Locale locale) {
  final code = locale.languageCode.trim().toLowerCase();
  return _supportedLanguageCodes.contains(code) ? code : 'en';
}

String tr(
  BuildContext context,
  String key, {
  Map<String, String> args = const {},
}) {
  final localeCode = languageCodeFromLocale(Localizations.localeOf(context));
  final localized = trByCode(localeCode, key, fallback: key);

  var result = localized;
  args.forEach((placeholder, value) {
    result = result.replaceAll('{$placeholder}', value);
  });
  return result;
}

String trByCode(
  String languageCode,
  String key, {
  String fallback = '',
  Map<String, String> args = const {},
}) {
  final normalized = _supportedLanguageCodes.contains(languageCode) ? languageCode : 'en';
  final localized = _translations[normalized]?[key] ?? _translations['en']?[key] ?? fallback;

  var result = localized;
  args.forEach((placeholder, value) {
    result = result.replaceAll('{$placeholder}', value);
  });
  return result;
}

